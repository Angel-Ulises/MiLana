import { readFileSync, writeFileSync } from 'node:fs';

const source = JSON.parse(readFileSync(new URL('../src/data/stateOccupations.json', import.meta.url), 'utf8'));
const meta = {
  period: source.period,
  source: {
    name: source.source.name,
    dataset: source.source.dataset,
    note: source.source.note,
    url: source.source.url,
  },
};
const rows = source.states.map((state) => [
  state.slug,
  state.state,
  state.occupations.map((item) => [
    item.occupationId, item.occupation, item.category, item.workforce, item.monthlyWage, item.records,
  ]),
]);
const browser = `// Generated by scripts/generar-state-occupations-browser.mjs. Do not edit.\n`
  + `const rows=${JSON.stringify(rows)};\n`
  + `const occupations=(items)=>items.map(([occupationId,occupation,category,workforce,monthlyWage,records])=>({occupationId,occupation,category,workforce,monthlyWage,records}));\n`
  + `export default {period:${JSON.stringify(meta.period)},source:${JSON.stringify(meta.source)},states:rows.map(([slug,state,items])=>({slug,state,occupations:occupations(items)}))};\n`;
writeFileSync(new URL('../src/data/stateOccupations.browser.js', import.meta.url), browser);
